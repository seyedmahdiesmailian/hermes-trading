def _local_ip() -> str:
    """This machine's own LAN address, via the default route (no literal)."""
    try:
        out = subprocess.run(['hostname', '-I'], capture_output=True,
                             text=True, timeout=5).stdout
        return out.split()[0] if out.split() else 'this host'
    except Exception:
        return 'this host'


def _win_ip() -> str:
    try:
        import bridge_client
        return str(bridge_client.WIN_IP)
    except Exception:
        return 'execution host'


def _git_count() -> str:
    try:
        return str(subprocess.run(['git', '-C', str(_REPO), 'rev-list',
                                   '--count', 'HEAD'],
                                  capture_output=True, text=True,
                                  timeout=10).stdout.strip() or '—')
    except Exception:
        return '—'


